/** The Calendar screen's logic (ADR 0035), including the real schedule payload core produces (checked-in sample generated by the service from the fixture calendar). */
class CalendarScreenTest {
    private val zone = ZoneId.of("Asia/Singapore")
    private val json = Json { ignoreUnknownKeys = true }
    private val view: ScheduleView = json.decodeFromString(checkNotNull(javaClass.getResource("/calendar-schedule.json")).readText())
    private fun day(d: Int) = LocalDate.of(2026, 10, d)
    private fun on(d: Int) = eventsOn(view.events, day(d), zone)
    private fun item(over: CalendarItem.() -> CalendarItem = { this }) =
        CalendarItem(title = "Design review", start = "2026-10-13T10:00:00+08:00", end = "2026-10-13T11:00:00+08:00", classification = "meeting", remind = true).over()

    @Test fun `the payload carries the revision and the feed status the screen shows`() {
        assertTrue(view.generation > 0); assertNotNull(view.snapshotRevision)
        assertEquals(view.generation, view.feed.generation); assertEquals(view.snapshotRevision, view.feed.snapshotRevision)
        assertEquals("ok", view.feed.syncState); assertEquals("url", view.feed.source); assertEquals("calendar.example.com", view.feed.host)
        assertTrue(view.feed.eventCount > 15); assertTrue(view.feed.configured)
    }

    @Test fun `a month is six Monday first weeks`() {
        val grid = monthGrid(YearMonth.of(2026, 10))
        assertEquals(42, grid.size); assertEquals(LocalDate.of(2026, 9, 28), grid.first()); assertEquals(LocalDate.of(2026, 11, 8), grid.last())
        assertEquals(31, grid.count { it.monthValue == 10 })
    }

    @Test fun `multi-day leave covers its days and never its exclusive end, and has no reminder`() {
        val leave = view.events.single { it.title == "Annual leave" }
        assertEquals("Leave", classLabel(leave)); assertTrue(leave.allDay)
        for (d in 19..21) assertTrue("day $d", onDay(leave, day(d), zone))
        assertFalse(onDay(leave, day(22), zone)); assertFalse(onDay(leave, day(18), zone))
        assertEquals("All day, Mon 19 Oct to Wed 21 Oct", dayTime(leave, day(19), zone))
        assertEquals("No reminder: all-day", reminderStatus(leave))
        assertEquals(listOf(Marker.Leave), dayMarkers(view.events.filter { it.title == "Annual leave" }, day(20), zone))
        assertTrue(on(20).any { it.title == "Incident review" } && on(20).any { it.title == "Annual leave" })  // a meeting on a leave day is still shown
    }

    @Test fun `a day lists timed events, all-day events, leave and Busy blocks in chronological order`() {
        val oct13 = on(13)
        assertEquals(listOf("Busy", "Design review"), oct13.map { it.title })  // 09:00 busy-title then 14:00
        assertEquals(oct13.map { millis(it.start) }, oct13.map { millis(it.start) }.sorted())
        assertEquals("09:00–10:00", dayTime(oct13[0], day(13), zone)); assertEquals("14:00–15:00", dayTime(oct13[1], day(13), zone))
        assertEquals(listOf("Weekly sync", "Busy"), on(12).map { it.title })  // 09:30 then the hidden 11:00 block
        assertEquals("Team offsite", on(27).single().title); assertEquals("All day, Tue 27 Oct to Wed 28 Oct", dayTime(on(27).single(), day(27), zone))
        assertTrue(on(14).none { it.title == "Cancelled planning meeting" })  // cancelled events are not on the schedule
        assertTrue(on(15).none { it.title == "Budget review" })  // declined
        assertEquals(emptyList<CalendarItem>(), on(24))  // an empty day
    }

    @Test fun `a Busy entry shows Busy and its interval and nothing hidden`() {
        val busy = on(12).single { it.classification == "busy_private" }
        assertEquals("Busy", scheduleTitle(busy)); assertEquals("Busy", classLabel(busy)); assertTrue(busy.redacted); assertNull(busy.location)
        assertEquals("11:00–12:00", dayTime(busy, day(12), zone))
        assertEquals("No reminder: details hidden", reminderStatus(busy))
        assertFalse(json.encodeToString(ScheduleView.serializer(), view).contains("Secret hospital"))
    }

    @Test fun `titles are never invented and reminder reasons are in words`() {
        assertEquals("Untitled event", scheduleTitle(on(16).single { it.titleMissing }))
        assertEquals("Recording reminder on", reminderStatus(item()))
        assertEquals("No reminder: personal appointment", reminderStatus(on(15).single { it.title == "Dentist appointment" }))
        assertEquals("No reminder: could not tell it is a meeting", reminderStatus(on(15).single { it.title == "Quiet time" }))
        assertEquals("No reminder: you are on leave", reminderStatus(item { copy(remind = false, remindBlocked = "on_leave") }))
    }

    @Test fun `times are shown in the phone's zone`() {
        val e = item { copy(start = "2026-10-13T02:00:00Z", end = "2026-10-13T03:00:00Z") }
        assertEquals("10:00–11:00", dayTime(e, day(13), zone))
        assertEquals("02:00–03:00", dayTime(e, day(13), ZoneId.of("UTC")))
        assertTrue(onDay(e, day(13), zone) && !onDay(e, day(12), zone))
        val late = item { copy(start = "2026-10-12T23:30:00Z", end = "2026-10-13T00:00:00Z") }  // 07:30 on the 13th in Singapore
        assertTrue(onDay(late, day(13), zone) && !onDay(late, day(12), zone))
    }

    @Test fun `upcoming meetings are only meetings still to finish, soonest first`() {
        val now = millis("2026-10-13T14:30:00+08:00")  // inside the 14:00 design review
        val up = upcomingMeetings(view.events, now, zone, limit = 3)
        assertEquals("Design review", up.first().title); assertTrue(up.all { it.classification == "meeting" })
        assertEquals(up.map { millis(it.start) }, up.map { millis(it.start) }.sorted())
        assertTrue(up.none { it.status == "cancelled" || it.response == "declined" })
    }

    @Test fun `the two clocks are separate and the state, source, count, error and cached lines are shown`() {
        val feed = FeedBrief(configured = true, freshness = "fresh", syncState = "ok", host = "week.ics", source = "upload", lastSuccessAt = "2026-10-13T10:00:00+08:00", eventCount = 5, generation = 7)
        val v = ScheduleView(generation = 7, feed = feed)
        val phoneChecked = millis("2026-10-13T10:20:00+08:00")
        val now = millis("2026-10-13T10:25:00+08:00")
        val lines = syncLines(v, phoneChecked, offline = false, nowMs = now).associate { it.label to it.value }
        assertEquals("Up to date", lines["State"]); assertEquals("Uploaded file (week.ics)", lines["Source"]); assertEquals("5", lines["Events"]); assertEquals("7", lines["Revision"])
        assertTrue(lines.getValue("Source last refreshed").endsWith("(25 min ago)"))
        assertTrue(lines.getValue("Phone last checked the hub").endsWith("(5 min ago)"))  // not the same moment
        assertFalse("Last error" in lines)
        val failed = syncLines(v.copy(feed = feed.copy(syncState = "error", error = "timeout")), phoneChecked, offline = false, nowMs = now).associate { it.label to it.value }
        assertEquals("Last refresh failed; showing the last good copy (cached)", failed["State"]); assertEquals("The calendar server took too long to answer.", failed["Last error"])
        val offline = syncLines(v, phoneChecked, offline = true, nowMs = now).associate { it.label to it.value }
        assertEquals("Up to date (cached)", offline["State"]); assertTrue(offline.getValue("Hub").startsWith("Not reachable"))
        assertTrue(isCached(feed, true) && !isCached(feed, false) && isCached(feed.copy(freshness = "stale"), false))
    }

    @Test fun `source and state wording for every case`() {
        assertEquals("None", sourceText(FeedBrief())); assertEquals("Calendar link (calendar.example.com)", sourceText(FeedBrief(configured = true, host = "calendar.example.com", source = "url")))
        assertEquals("No calendar set up", syncStateText(FeedBrief(syncState = "not_configured"))); assertEquals("Refreshing", syncStateText(FeedBrief(syncState = "refreshing")))
        assertEquals("The calendar server answered 503.", errorText("http_503")); assertNull(errorText(null)); assertEquals("The calendar could not be loaded.", errorText("whatever"))
    }
}
